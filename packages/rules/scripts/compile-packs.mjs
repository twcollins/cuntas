// Compiles rules/**/*.yaml into src/packs/generated.ts so packs load identically in Node and the browser.
// Usage: node scripts/compile-packs.mjs [--check]
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rulesDir = join(root, "rules");
const outFile = join(root, "src/packs/generated.ts");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(join(dir, d.name)) : d.name.endsWith(".yaml") ? [join(dir, d.name)] : [],
  );
}

const files = walk(rulesDir).sort();
const packs = {};
const manifest = [];
for (const file of files) {
  const text = readFileSync(file, "utf8");
  const data = parse(text);
  const key = relative(rulesDir, file).replace(/\.yaml$/, "");
  packs[key] = data;
  manifest.push({ key, version: data.version, sha256: createHash("sha256").update(text).digest("hex") });
}

const output =
  "// GENERATED by scripts/compile-packs.mjs from rules/**/*.yaml. Do not edit by hand.\n" +
  `export const RAW_PACKS: Record<string, unknown> = ${JSON.stringify(packs, null, 2)};\n\n` +
  `export const MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== output) {
    console.error("src/packs/generated.ts is stale. Run: pnpm build:packs");
    process.exit(1);
  }
  console.log("Rule packs up to date.");
} else {
  writeFileSync(outFile, output);
  console.log(`Compiled ${files.length} rule packs.`);
}
